import type { Building, ConstructionCost, Recipe, RecipeInput, RecipeOutput } from '@/shared/@types/building.type'

/** An invalid plan has no trustworthy production totals or graph. */
export interface ProductionPlanIssue {
  code: 'cycle' | 'invalid-rate'
  itemId: string
  message: string
  path?: readonly string[]
}

/** One physical coproduct rate assigned once to a specific consuming recipe. */
export interface ByproductAllocation {
  sourceItemId: string
  consumerItemId: string
  itemId: string
  amountPerMinute: number
}

/** Unsatisfied external input in items/min, including non-raw items without a standalone recipe. */
export interface RawInputDemand {
  itemId: string
  amountPerMinute: number
}

/** Aggregated demand for one selected recipe; machine load is fractional and physical count is rounded up. */
export interface ProductionStep {
  itemId: string
  buildingId: string
  buildingName: string
  /** Net items/min for self-recycling recipes; otherwise the regular recipe output rate. */
  recipeOutputIpm: number
  targetIpm: number
  buildingLoad: number
  buildingCount: number
  /** Source energy use per machine in MJ; undefined means unknown. */
  buildingPower?: number
  /** Source-backed materials required to construct one machine; undefined means unknown. */
  buildingConstructionCost?: readonly ConstructionCost[]
  supplyCount: number
  /** Self-input is handled internally and excluded from external dependencies. */
  inputs: readonly RecipeInput[]
  recipeId?: string
  /** Rate that circulates inside this recipe, not additional external demand. */
  recycledIpm?: number
  /** Source-confirmed byproducts generated by the configured load; allocation is tracked separately. */
  extraOutputs?: readonly RecipeOutput[]
}

/**
 * Physical machines required by the complete plan, grouped by building type.
 * Multiple recipe steps using the same machine are additive because the planner models continuous production.
 */
export type RequiredBuilding = Pick<
  ProductionStep,
  'buildingId' | 'buildingName' | 'buildingCount' | 'buildingPower' | 'buildingConstructionCost'
>

/** Derived steady-state result shared by every view; issues make its totals and graph unavailable. */
export interface ProductionPlan {
  targetId: string
  targetIpm: number
  /** External raw target without an authorized synthesis route; selects the terminal-input presentation. */
  isRawTarget: boolean
  supplyCountByItem: Record<string, number>
  supplyCountInventory: Record<string, number>
  steps: ProductionStep[]
  /** Remaining external item demand after configured supply is applied. */
  rawInputs: readonly RawInputDemand[]
  stats: { buildings: number; power: number | null }
  issues: readonly ProductionPlanIssue[]
  /** Actual assigned coproduct flows, excluding unused generated quantities. */
  byproductAllocations?: readonly ByproductAllocation[]
}

/** Catalog identities and editable inputs; target and supply quantities are rates in items/min. */
export interface BuildProductionPlanParams {
  buildings: readonly Building[]
  producerBuildingsByItemId: ReadonlyMap<string, readonly Building[]>
  targetId: string
  targetIpm: number
  /** Catalog classification before resolving an explicit raw synthesis selection. */
  isRawTarget: boolean
  /** Authoritative raw item IDs distinguish external minerals from broken recipe references. */
  rawItemIds?: ReadonlySet<string>
  /** Catalog-backed items acquired outside machines, distinct from raw minerals and coproducts. */
  externalItemIds?: ReadonlySet<string>
  supplyCountByItem: Record<string, number>
  /** An explicit per-product recipe ID, independent from machine and file ordering. */
  recipeIdByItemId?: Record<string, string>
}

/** Resolves a product's machine and recipe consistently, with explicit selections checked against that output. */
export interface PlanResolver {
  buildings: readonly Building[]
  getBuildingForItem: (itemId: string) => Building | null
  getRecipeForItem: (itemId: string) => Recipe | null
  /** True only for an exact explicit recipe ID producing this item, never for a fallback. */
  hasSelectedRecipeForItem: (itemId: string) => boolean
}
